/**
 * Returns [[SW_lng, SW_lat], [NE_lng, NE_lat]] for an ISO 3166-1 alpha-2 code.
 * Falls back to the Mapbox Geocoding API for countries not in the static table.
 */
export async function getCountryBounds(isoCode, accessToken) {
  const code = isoCode.toUpperCase();

  if (BOUNDS[code]) return BOUNDS[code];

  try {
    const res = await fetch(
      `https://api.mapbox.com/geocoding/v5/mapbox.places/${encodeURIComponent(code)}.json` +
      `?types=country&access_token=${accessToken}`
    );
    const data = await res.json();
    const bbox = data.features?.[0]?.bbox;
    if (bbox) return [[bbox[0], bbox[1]], [bbox[2], bbox[3]]];
  } catch {
    // network or parse error — caller handles null
  }

  return null;
}
